import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { query, type HookCallback, type SDKMessage } from "@anthropic-ai/claude-agent-sdk";
import { buildSite } from "./build.js";
import { config } from "./config.js";
import { formatInteractions, testInteractions, type InteractionReport } from "./interactions.js";
import { lintSite, type LintReport } from "./lint.js";
import { buildSystemPrompt, buildUserPrompt } from "./prompt.js";
import { resolveProduct } from "./product.js";
import { scaffoldSite, slugify } from "./scaffold.js";
import { SITE_TOOL_NAMES, createSiteTools } from "./tools.js";

export type PageRequest = {
  brief: string;
  slug?: string;
  assets?: string[];
  model?: string;
  maxBudgetUsd?: number;
  maxTurns?: number;
  /** Replace an existing sites/<slug> instead of creating <slug>-2. */
  replace?: boolean;
  /** Product folder (brand, voice, facts): a path, or "none". Default: LPA_PRODUCT_DIR / PRODUCT_DIR, then the nearest product/. */
  product?: string;
};

export type AgentEvent =
  | { type: "scaffolded"; slug: string; dir: string }
  | { type: "text"; text: string }
  | { type: "tool"; name: string; detail: string }
  | { type: "verify"; lint: { ok: boolean; errors: number; warnings: number; placeholders: number }; build: boolean; interactions?: { ok: boolean; checks: number; failed: number } }
  | { type: "done"; result: PageResult };

export type PageResult = {
  slug: string;
  dir: string;
  outDir: string;
  ok: boolean;
  status: "success" | "agent_error" | "verification_failed" | "aborted";
  summary: string;
  costUsd: number;
  turns: number;
  durationMs: number;
  sessionId?: string;
  lint?: Pick<LintReport, "ok" | "errors" | "warnings" | "placeholders">;
  buildOk?: boolean;
  interactions?: { ok: boolean; checks: number; failed: number; report: string };
  error?: string;
  /** The product folder the page was built for, if any. */
  product?: { dir: string; name: string } | null;
};

const BUILTIN_TOOLS = ["Read", "Write", "Edit", "Glob", "Grep"];

/** Files the agent may read but never write (design system, brand output, brief, run data). */
export const PROTECTED_PATHS = [
  "styles/tokens.css",
  "styles/brand.css",
  "app/fonts.ts",
  "app/icon.svg",
  "components/ui/",
  "components/site/",
  "components/library/",
  "node_modules/",
  "out/",
  ".next/",
  ".lpa/",
  "BRIEF.md",
  "PRODUCT.md",
  "public/assets/brand/",
];

/**
 * PreToolUse guard: confine file tools to the site folder, keep the design
 * system read-only, and enforce the order PLAN.md → set_brand → code.
 */
export function confineTo(siteDir: string): HookCallback {
  const root = path.resolve(siteDir) + path.sep;
  return async (input) => {
    if (input.hook_event_name !== "PreToolUse") return {};
    const args = (input.tool_input ?? {}) as Record<string, unknown>;
    const deny = (reason: string) => ({
      hookSpecificOutput: { hookEventName: "PreToolUse" as const, permissionDecision: "deny" as const, permissionDecisionReason: reason },
    });
    const pattern = typeof args.pattern === "string" && input.tool_name === "Glob" ? args.pattern : "";
    if (pattern && (path.isAbsolute(pattern) || pattern.split(/[\\/]/).includes(".."))) return deny("Glob patterns must stay inside the site folder.");
    const target = (args.file_path ?? args.path ?? args.notebook_path) as string | undefined;
    if (!target) return {};
    const abs = path.resolve(siteDir, target);
    const rel = path.relative(siteDir, abs).split(path.sep).join("/");
    const writing = input.tool_name === "Write" || input.tool_name === "Edit";
    let reason: string | undefined;
    if (!(abs + path.sep).startsWith(root) && abs !== root.slice(0, -1)) reason = `Access outside the site folder is not allowed (${target}).`;
    else if (writing && PROTECTED_PATHS.some((p) => rel === p || rel.startsWith(p)))
      reason = rel.startsWith("styles/brand") || rel.startsWith("app/fonts") || rel.startsWith("app/icon")
        ? `${rel} is generated by the set_brand tool. Call set_brand to change colours, fonts or corners.`
        : `${rel} is read-only (design system or run data). Put new or adapted sections in components/custom/.`;
    else if (writing && rel !== "PLAN.md" && !existsSync(path.join(siteDir, "PLAN.md")))
      reason = "Write PLAN.md first: audience, brand, buyer questions, and one section per question marked library / adapted / new (see the workflow).";
    else if (writing && rel !== "PLAN.md" && isDefaultBrand(siteDir))
      reason = "Call set_brand first, with the product's own colours and fonts, so every section is built on the right brand.";
    return reason ? deny(reason) : {};
  };
}

function isDefaultBrand(siteDir: string): boolean {
  const p = path.join(siteDir, "styles", "brand.css");
  return existsSync(p) && readFileSync(p, "utf8").includes("DEFAULT BRAND");
}

function describeTool(name: string, input: Record<string, unknown>): string {
  const short = name.replace(/^mcp__site__/, "");
  const target = (input.file_path ?? input.path ?? input.pattern ?? input.viewport ?? "") as string;
  return target ? `${short} ${String(target).replace(/^.*\/sites\/[^/]+\//, "")}` : short;
}

/**
 * Scaffold a site from the template and let the agent compose, lint, build and
 * visually review the page. Ends with an independent lint, build and interaction test.
 */
export async function buildLandingPage(
  req: PageRequest,
  opts: { onEvent?: (e: AgentEvent) => void; abortController?: AbortController } = {},
): Promise<PageResult> {
  const emit = opts.onEvent ?? (() => {});
  const started = Date.now();
  const firstLine = req.brief.trim().split("\n")[0] ?? "page";
  const product = resolveProduct(req.product);
  const site = scaffoldSite({ slug: slugify(req.slug ?? firstLine), brief: req.brief, assets: req.assets, overwrite: req.replace && Boolean(req.slug), product });
  emit({ type: "scaffolded", slug: site.slug, dir: site.dir });

  const abortController = opts.abortController ?? new AbortController();
  let summary = "";
  let costUsd = 0;
  let turns = 0;
  let sessionId: string | undefined;
  let agentError: string | undefined;
  let fatal = false;

  try {
    const q = query({
      prompt: buildUserPrompt(site.slug, { product: site.product?.name }),
      options: {
        cwd: site.dir,
        model: req.model ?? config.model,
        systemPrompt: buildSystemPrompt(),
        tools: BUILTIN_TOOLS,
        allowedTools: [...BUILTIN_TOOLS, ...SITE_TOOL_NAMES],
        mcpServers: { site: createSiteTools(site.dir) },
        permissionMode: "dontAsk",
        settingSources: [],
        hooks: { PreToolUse: [{ matcher: "Read|Write|Edit|Glob|Grep", hooks: [confineTo(site.dir)] }] },
        maxTurns: req.maxTurns ?? config.maxTurns,
        maxBudgetUsd: req.maxBudgetUsd ?? config.maxBudgetUsd,
        abortController,
        env: { ...process.env, CLAUDE_AGENT_SDK_CLIENT_APP: "corporate-landing-agent/0.2.0" },
      },
    });

    for await (const msg of q as AsyncIterable<SDKMessage>) {
      if (msg.type === "system" && "session_id" in msg) sessionId ??= msg.session_id;
      if (msg.type === "system" && msg.subtype === "api_retry") {
        // Credentials won't fix themselves: fail fast instead of backing off for minutes.
        if (msg.error === "authentication_failed" || msg.error === "billing_error") {
          agentError = `${msg.error}: log in with your Claude subscription (run \`claude\`, then /login, or set CLAUDE_CODE_OAUTH_TOKEN from \`claude setup-token\`), or set ANTHROPIC_API_KEY.`;
          fatal = true;
          abortController.abort();
          break;
        }
        emit({ type: "text", text: `API retry ${msg.attempt}/${msg.max_retries} (${msg.error}, HTTP ${msg.error_status ?? "n/a"})` });
      }
      if (msg.type === "assistant" && !msg.parent_tool_use_id) {
        for (const block of msg.message.content) {
          if (block.type === "text" && block.text.trim()) emit({ type: "text", text: block.text.trim() });
          if (block.type === "tool_use") emit({ type: "tool", name: block.name, detail: describeTool(block.name, block.input as Record<string, unknown>) });
        }
      }
      if (msg.type === "result") {
        costUsd = msg.total_cost_usd;
        turns = msg.num_turns;
        sessionId = msg.session_id;
        if (msg.subtype === "success") summary = msg.result;
        else agentError = `${msg.subtype}${"errors" in msg && Array.isArray(msg.errors) ? `: ${msg.errors.join("; ")}` : ""}`;
      }
    }
  } catch (err) {
    if (!fatal) agentError = abortController.signal.aborted ? "aborted" : (err as Error).message;
  }
  const aborted = abortController.signal.aborted && !fatal;

  // Independent verification: never trust the agent's own claim.
  const lint = lintSite(site.dir, { denylist: config.denylist });
  const build = aborted || fatal ? { ok: false } : await buildSite(site.dir);
  let interactions: InteractionReport | undefined;
  if (build.ok) {
    try {
      interactions = await testInteractions(site.dir);
    } catch (err) {
      interactions = { ok: false, checks: [], errors: [`Interaction test failed to run: ${(err as Error).message}`] };
    }
  }
  const ix = interactions && {
    ok: interactions.ok,
    checks: interactions.checks.length,
    failed: interactions.checks.filter((c) => !c.pass).length + interactions.errors.length,
  };
  emit({ type: "verify", lint: { ok: lint.ok, errors: lint.errors, warnings: lint.warnings, placeholders: lint.placeholders }, build: build.ok, interactions: ix });

  const status: PageResult["status"] = aborted
    ? "aborted"
    : agentError
      ? "agent_error"
      : lint.ok && build.ok && (interactions?.ok ?? false)
        ? "success"
        : "verification_failed";

  const result: PageResult = {
    slug: site.slug,
    dir: site.dir,
    outDir: path.join(site.dir, "out"),
    ok: status === "success",
    status,
    summary,
    costUsd,
    turns,
    durationMs: Date.now() - started,
    sessionId,
    lint: { ok: lint.ok, errors: lint.errors, warnings: lint.warnings, placeholders: lint.placeholders },
    buildOk: build.ok,
    interactions: ix && interactions ? { ...ix, report: formatInteractions(interactions) } : undefined,
    error: agentError,
    product: site.product ? { dir: site.product.dir, name: site.product.name } : null,
  };
  writeFileSync(path.join(site.dir, ".lpa", "result.json"), JSON.stringify(result, null, 2));
  emit({ type: "done", result });
  return result;
}
