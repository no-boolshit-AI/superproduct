/** Pull request title/body from the run record. */
import { prdSection } from "./plan.js";
import type { Profile } from "./profile.js";
import type { RunRecord } from "./run-record.js";
import { commitUrl, type RepoRef } from "./github.js";

const MAX_BODY = 60_000;

export function prTitle(run: RunRecord, profile: Profile): string {
  const t = run.title.replace(/\s+/g, " ").trim();
  if (profile.git.commitStyle !== "conventional" || /^[a-z]+(\(.+\))?!?:/.test(t)) return t.slice(0, 120);
  return `feat: ${t.charAt(0).toLowerCase()}${t.slice(1)}`.slice(0, 120);
}

export function prBody(run: RunRecord, profile: Profile, repo: RepoRef, prd: string): string {
  const out: string[] = [];
  const summary = prdSection(prd, "Summary");
  out.push("## Summary", "", summary || run.request.split("\n").slice(0, 6).join("\n"), "");
  if (run.issue) out.push(`Closes #${run.issue.number}`, "");

  out.push("## Milestones", "");
  for (const m of run.milestones) {
    const sha = m.commit ? ` ([\`${m.commit.slice(0, 7)}\`](${commitUrl(repo, m.commit) ?? "#"}))` : "";
    const box = m.status === "done" || m.status === "done_with_issues" ? "x" : " ";
    out.push(`- [${box}] **${m.id}: ${m.title}**${sha}${m.summary ? `: ${m.summary.split("\n")[0].slice(0, 300)}` : ""}`);
    if (m.knownIssues) out.push(`  - ⚠️ Known issues: ${m.knownIssues.slice(0, 500)}`);
  }
  out.push("");

  if (run.verification) {
    out.push("## Verification", "", "| Check | Command | Result |", "|---|---|---|");
    for (const c of run.verification.checks)
      out.push(`| ${c.name} | \`${c.command.replace(/\|/g, "\\|")}\` | ${c.ok ? "✅ passed" : `❌ failed (exit ${c.code})`} |`);
    if (!run.verification.checks.length) out.push("| (none configured) | | |");
    out.push("");
    const failed = run.verification.checks.filter((c) => !c.ok);
    for (const c of failed) out.push(`<details><summary>${c.name} output</summary>\n\n\`\`\`\n${c.tail.slice(-3000)}\n\`\`\`\n</details>`, "");
  }

  if (run.review) {
    const open = run.review.findings.filter((f) => f.severity === "minor" || f.severity === "nit");
    out.push("## Automated review", "", `${run.review.verdict === "approve" ? "Approved" : "Changes were requested and addressed"} after ${run.review.rounds} round(s). ${run.review.summary}`, "");
    if (open.length) {
      out.push("Remaining minor notes:");
      for (const f of open.slice(0, 15)) out.push(`- ${f.file ? `\`${f.file}${f.line ? `:${f.line}` : ""}\` ` : ""}${f.title}`);
      out.push("");
    }
  }

  const assumptions = prdSection(prd, "Assumptions(?: and open questions)?");
  if (assumptions) out.push("## Assumptions and open questions", "", assumptions, "");

  if (run.toolingCommit) out.push(`> The first commit (\`${run.toolingCommit.slice(0, 7)}\`) adds AI dev tooling (${profile.tooling.recipes.join(", ")}), as configured for this project.`, "");

  const used = out.join("\n").length;
  const room = MAX_BODY - used - 600;
  if (room > 1000) out.push("<details><summary>PRD</summary>", "", prd.length > room ? prd.slice(0, room) + "\n\n…(truncated)" : prd, "", "</details>", "");
  out.push("---", `_Generated by dev-agent · run \`${run.id}\` · Claude spend $${run.costUsd.toFixed(2)}_`);
  return out.join("\n").slice(0, MAX_BODY);
}

/** Conventional-commit subject for a milestone. */
export function commitSubject(raw: string, style: "conventional" | "plain", fallbackType = "feat"): string {
  let s = raw.split("\n")[0].replace(/\s+/g, " ").trim().replace(/\.$/, "");
  if (style === "conventional" && !/^[a-z]+(\([^)]+\))?!?:\s/.test(s)) s = `${fallbackType}: ${s.charAt(0).toLowerCase()}${s.slice(1)}`;
  return s.slice(0, 100);
}
